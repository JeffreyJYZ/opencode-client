import type { CSSProperties } from "react";
import { sanitizeHtml } from "./markdownBlocks";
import { CopyButton } from "./RowActionButtons";
import { CODE_STYLE } from "./rowStyles";
import { useHighlightedCode } from "./useHighlightedCode";

/**
 * A fenced code block: plain until the highlighter settles, then Shiki's HTML
 * (M2.3).
 *
 * Shiki names its token colours as `--shiki-*` custom properties on the `<pre>`
 * (the dual theme, no inline colour); `base.css` maps the pair to `data-theme`,
 * so no colour is written here. The block's own surface is `--oc-surface-raised`
 * and the face is `--oc-font-code` through `base.css`'s `pre` rule — the code
 * face is a token, never a family here (spec 030 §Two font roles).
 *
 * The block carries its own copy affordance (M5.2): the fence's **source text**,
 * never the rendered HTML, so what lands on the clipboard is what the fence said.
 */

const BLOCK_STYLE: CSSProperties = {
	...CODE_STYLE,
	margin: 0,
	padding: "var(--oc-space-3)",
	borderRadius: "var(--oc-radius)",
	background: "var(--oc-surface-raised)",
	overflowX: "auto",
};

/** The block and its copy button, stacked; the button hugs its own text. */
const WRAP_STYLE: CSSProperties = {
	display: "flex",
	flexDirection: "column",
	gap: "var(--oc-space-1)",
};

export function CodeBlock({
	code,
	language,
}: {
	readonly code: string;
	readonly language: string;
}) {
	const html = useHighlightedCode(code, language);
	return (
		<div style={WRAP_STYLE}>
			{html === null ? (
				<pre style={BLOCK_STYLE}>
					<code>{code}</code>
				</pre>
			) : (
				// The highlighted HTML is generated here from already-escaped text;
				// DOMPurify still runs over it so one boundary covers every innerHTML insert.
				// biome-ignore lint/security/noDangerouslySetInnerHtml: generated by Shiki from the fence's escaped text, then sanitised
				<div style={BLOCK_STYLE} dangerouslySetInnerHTML={{ __html: sanitizeHtml(html) }} />
			)}
			<CopyButton text={code} />
		</div>
	);
}
