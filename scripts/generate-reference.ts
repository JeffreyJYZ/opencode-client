#!/usr/bin/env bun
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import ts from "typescript";
import {
	APP_VERSION,
	HOST_API_VERSION,
	HOST_GLOBAL,
	PLUGIN_DATA_DIR,
	PLUGIN_DATA_MAX_BYTES,
	PLUGIN_ENTRY_DEFAULT,
	PLUGIN_HOST_GLOBAL_SPECIFIERS,
	PLUGIN_OUT_DIR,
	PLUGIN_REFUSED_SPECIFIERS,
	PLUGIN_SOURCE_DIR,
	PLUGIN_SOURCE_ENTRY,
	PLUGIN_STORAGE_KEY_PATTERN,
	PLUGIN_STORAGE_SEPARATOR,
} from "@/constants/plugins";
import { SETTINGS_SECTION_ID } from "@/constants/settings";
import { PLUGIN_CAPABILITIES, PLUGIN_ENFORCED_CAPABILITIES } from "@/plugins/capabilities";
import { FAULT_AREAS, FAULT_REASONS } from "@/plugins/faults";
import { isLockedSlot, SLOTS } from "@/plugins/slots";

/**
 * `bun scripts/generate-reference.ts [--out <path>]` — the **only** writer of
 * `src/docs/reference.generated.ts` (M4.8, spec 040 §Build, install, develop: "the
 * in-app API reference is generated from the SDK types and the slot/registry
 * tables"), so the page can never drift from the code it documents. Two sources,
 * no hand-typed list:
 *
 * - the **SDK types**: the TypeScript checker reads the `Host` type of
 *   `src/plugins/sdk.ts` and prints each member with its own signature. A registry
 *   is a member whose signature carries a `register` method — the one property the
 *   host's own API gives a registry and not a service — so adding a member to
 *   `Host` adds a row here, and nothing else needs touching.
 * - the **runtime tables**: the slot tuple, the capability labels, the locked
 *   areas, the fault vocabulary and the entry-file contract's constants.
 *
 * `src/docs/reference.test.ts` regenerates into a temp path and diffs, so a file
 * that no longer matches its generator fails `bun test` rather than shipping stale.
 */

const ROOT = resolve(import.meta.dir, "..");
const SDK = join(ROOT, "src/plugins/sdk.ts");
const DEFAULT_OUT = join(ROOT, "src/docs/reference.generated.ts");

/** The one marker that separates a registry from a service in an SDK signature. */
const REGISTER_METHOD = "register";

/** Every member of the `Host` type, with the signature the checker resolves. */
export function hostMembers(): { name: string; signature: string; kind: "registry" | "service" }[] {
	const read = ts.readConfigFile(join(ROOT, "tsconfig.app.json"), ts.sys.readFile);
	if (read.error !== undefined)
		throw new Error("generate-reference: tsconfig.app.json unreadable");
	const parsed = ts.parseJsonConfigFileContent(read.config, ts.sys, ROOT);
	const program = ts.createProgram({ rootNames: [SDK], options: parsed.options });
	const checker = program.getTypeChecker();
	const source = program.getSourceFile(SDK);
	if (source === undefined) throw new Error(`generate-reference: no ${SDK}`);
	for (const statement of source.statements) {
		if (!ts.isTypeAliasDeclaration(statement)) continue;
		if (statement.name.text !== "Host") continue;
		const type = checker.getTypeAtLocation(statement.type);
		return type.getProperties().map((property) => {
			const signature = checker
				.typeToString(checker.getTypeOfSymbolAtLocation(property, statement))
				.replaceAll(/\s+/g, " ")
				.trim();
			return {
				name: property.getName(),
				signature,
				kind: signature.includes(REGISTER_METHOD) ? "registry" : "service",
			};
		});
	}
	throw new Error("generate-reference: src/plugins/sdk.ts declares no Host type");
}

/** The whole reference, as the generated module's data. */
export function referenceData() {
	const host = hostMembers();
	return {
		appVersion: APP_VERSION,
		apiVersion: HOST_API_VERSION,
		host,
		registries: host
			.filter((member) => member.kind === "registry")
			.map((member) => member.name),
		services: host.filter((member) => member.kind === "service").map((member) => member.name),
		slots: SLOTS.map((name) => ({ name, locked: isLockedSlot(name) })),
		lockedAreas: SLOTS.filter(isLockedSlot).map((name) => name),
		capabilities: PLUGIN_CAPABILITIES.map((label) => ({
			label,
			enforced: (PLUGIN_ENFORCED_CAPABILITIES as readonly string[]).includes(label),
		})),
		managerSection: SETTINGS_SECTION_ID.plugins,
		lockedAreaFault: FAULT_REASONS.lockedArea,
		slotsFaultArea: FAULT_AREAS.slots,
		entry: {
			defaultName: PLUGIN_ENTRY_DEFAULT,
			sourceDir: PLUGIN_SOURCE_DIR,
			outDir: PLUGIN_OUT_DIR,
			sourceNames: PLUGIN_SOURCE_ENTRY,
			globals: HOST_GLOBAL,
			rewritten: PLUGIN_HOST_GLOBAL_SPECIFIERS,
			refused: PLUGIN_REFUSED_SPECIFIERS,
			dataDir: PLUGIN_DATA_DIR,
			dataMaxBytes: PLUGIN_DATA_MAX_BYTES,
			storageSeparator: PLUGIN_STORAGE_SEPARATOR,
			storageKeyPattern: PLUGIN_STORAGE_KEY_PATTERN.source,
		},
	} as const;
}

const HEADER = `/**
 * GENERATED by \`bun scripts/generate-reference.ts\` — **do not edit by hand**.
 *
 * The in-app API reference's data (M4.8, spec 040 §Build, install, develop): the
 * \`Host\` type's own members with their signatures, read from
 * \`src/plugins/sdk.ts\` by the TypeScript checker, plus the slot, capability,
 * fault and entry-file tables the code declares. \`ReferenceSection\` renders it,
 * and \`reference.test.ts\` fails when this file and the generator disagree.
 */
`;

/** The file's text, so the test can compare without writing into the repo. */
export function renderReference(): string {
	return `${HEADER}\nexport const REFERENCE = ${JSON.stringify(referenceData(), null, "\t")} as const;\n`;
}

/** The output path: `--out <path>` overrides the committed one. */
function outPath(args: readonly string[]): string {
	const at = args.indexOf("--out");
	return at === -1 ? DEFAULT_OUT : resolve(args[at + 1] ?? "");
}

if (import.meta.main) {
	const out = outPath(process.argv.slice(2));
	mkdirSync(dirname(out), { recursive: true });
	writeFileSync(out, renderReference());
	const { registries, slots } = referenceData();
	console.log(
		`generate-reference: ${out} (${registries.length} registries, ${slots.length} slots)`,
	);
}
